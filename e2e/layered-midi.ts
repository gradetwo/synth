/**
 * A two-track (format 1) MIDI file, built inline so the tests do not carry a
 * binary fixture: a bass note on track 1 and a lead note on track 2.
 */
export function layeredMidiFile(): Buffer {
  const bass = [
    0x00, 0xff, 0x03, 0x04, 0x42, 0x61, 0x73, 0x73, // track name "Bass"
    0x00, 0x90, 0x30, 0x64,
    0x83, 0x60, 0x80, 0x30, 0x40,
    0x00, 0xff, 0x2f, 0x00,
  ];
  const lead = [
    0x00, 0xff, 0x03, 0x04, 0x4c, 0x65, 0x61, 0x64, // track name "Lead"
    0x00, 0x90, 0x3e, 0x64,
    0x83, 0x60, 0x80, 0x3e, 0x40,
    0x00, 0xff, 0x2f, 0x00,
  ];
  return Buffer.from([
    0x4d, 0x54, 0x68, 0x64, 0, 0, 0, 6, 0, 1, 0, 2, 0x01, 0xe0,
    0x4d, 0x54, 0x72, 0x6b, 0, 0, 0, bass.length, ...bass,
    0x4d, 0x54, 0x72, 0x6b, 0, 0, 0, lead.length, ...lead,
  ]);
}
